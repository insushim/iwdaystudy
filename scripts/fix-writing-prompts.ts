const files = [
  "src/lib/curriculum/grade1.ts",
  "src/lib/curriculum/grade2.ts",
  "src/lib/curriculum/grade3.ts",
  "src/lib/curriculum/grade4.ts",
  "src/lib/curriculum/grade5.ts",
  "src/lib/curriculum/grade6.ts",
  "src/lib/curriculum/generators/writing-creative-generator.ts",
];

const root = path.join(__dirname, "..");
const usedKeys = new Set<string>();
let total = 0;
for (const f of files) {
  const fp = path.join(root, f);
  let src = fs.readFileSync(fp, "utf8");
  let count = 0;
  for (const [oldS, newS] of Object.entries(R)) {
    const needle = `"${oldS}"`;
    if (src.includes(needle)) {
      src = src.split(needle).join(`"${newS}"`);
      usedKeys.add(oldS);
      count++;
    }
  }
  fs.writeFileSync(fp, src);
  console.log(`${f}: ${count}건 교체`);
  total += count;
}
console.log(`총 ${total}건`);
const missed = Object.keys(R).filter((k) => !usedKeys.has(k));
if (missed.length) {
  console.log(`\n⚠️ 매칭 실패 ${missed.length}건:`);
  for (const k of missed) console.log(`  "${k}"`);
}
