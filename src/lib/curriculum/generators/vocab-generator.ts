function shuffle<T>(arr: T[], random: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function generateVocabPool(grade: number, seed: number): VocabEntry[] {
  const random = seededRandom(seed * 7 + grade * 31);
  let pool: WordData[];
  if (grade <= 2) pool = WORDS_12;
  else if (grade <= 4) pool = [...WORDS_12, ...WORDS_34];
  else pool = [...WORDS_34, ...WORDS_56];

  const shuffled = shuffle(pool, random);
  return shuffled.map((w) => ({ meanings: w.meanings, answer: w.word }));
}
