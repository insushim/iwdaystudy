export function generateWritingPool(grade: number, seed: number): string[] {
  const random = seededRandom(seed * 19 + grade * 59);
  let pool: string[];
  if (grade <= 2) pool = [...WRITING_12, ...W12X];
  else if (grade <= 4) pool = [...WRITING_12, ...W12X, ...WRITING_34, ...W34X];
  else pool = [...WRITING_34, ...W34X, ...WRITING_56, ...W56X];
  return shuffle(pool, random);
}

export function generateCreativePool(
  grade: number,
  seed: number,
): KnowledgeEntry[] {
  const random = seededRandom(seed * 23 + grade * 61);
  let pool: KnowledgeEntry[];
  if (grade <= 2) pool = [...CREATIVE_12, ...CREATIVE_12_X];
  else if (grade <= 4) pool = [...CREATIVE_34, ...CREATIVE_34_X];
  else pool = [...CREATIVE_56, ...CREATIVE_56_X];
  return shuffle(pool, random);
}
