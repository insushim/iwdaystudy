/**
 * 문항의 (과목, 학년, unit)로 성취기준 code를 조회한다.
 * 매핑이 없으면 null(기존과 동일 — 억지 매핑보다 미표기가 안전).
 */
export function lookupStandardCode(
  subject: string,
  grade: number,
  unit: string | undefined,
): string | null {
  if (!unit) return null;
  if (subject === "math") return MATH_STANDARD_MAP[grade]?.[unit] ?? null;
  return null;
}
